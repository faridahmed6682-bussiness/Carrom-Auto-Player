// Minimal app module build file for Carrom-Auto-Player.
// Written for this export from the carrom code's actual imports at ea02d43:
//   - Compose Material3 + ui (CarromCalibrationDialog.kt)
//   - androidx.activity.compose (photo picker launcher in the dialog)
//   - kotlinx-coroutines (CarromShotMemoryStore.kt)
//   - org.json is part of Android, no dependency needed
//   - junit + robolectric + coroutines-test (extracted carrom tests)
// NOT needed and intentionally left out: Firebase, google-services,
// secrets plugin, Room, Camera, Coil, Retrofit/Moshi, Play services.
// NOTE: AndroidManifest.xml (app/src/main/AndroidManifest.xml) and the
// launcher Activity (CarromMainActivity.kt, package com.example.game) are
// present — the module builds a debug APK. The shell hosts calibration
// only; the live auto-play loop is NOT in this repo (see README.md).
plugins {
  alias(libs.plugins.android.application)
  alias(libs.plugins.kotlin.compose)
}

android {
  namespace = "com.example"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "com.example.carromautoplayer"
    minSdk = 24
    targetSdk = 36
    versionCode = 1
    versionName = "1.0"
  }

  signingConfigs {
    create("release") {
      val keystorePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"
      storeFile = file(keystorePath)
      storePassword = System.getenv("STORE_PASSWORD")
      keyAlias = "upload"
      keyPassword = System.getenv("KEY_PASSWORD")
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isMinifyEnabled = false
      signingConfig = signingConfigs.getByName("release")
    }
    debug {
      signingConfig = signingConfigs.getByName("debugConfig")
    }
  }

  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }

  buildFeatures {
    compose = true
    buildConfig = true
  }

  testOptions { unitTests { isIncludeAndroidResources = true } }
}

dependencies {
  implementation(platform(libs.androidx.compose.bom))
  implementation(libs.androidx.activity.compose)
  implementation(libs.androidx.compose.material.icons.core)
  implementation(libs.androidx.compose.material.icons.extended)
  implementation(libs.androidx.compose.material3)
  implementation(libs.androidx.compose.ui)
  implementation(libs.androidx.compose.ui.graphics)
